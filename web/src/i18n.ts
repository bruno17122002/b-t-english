const DICTS: Record<Lang, Record<MsgKey, string>> = { vi: VI, en: EN }

export function translate(lang: Lang, key: MsgKey, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? VI[key]
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

export function useT() {
  const lang = useApp((s) => s.lang)
  return (key: MsgKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export function errorKey(code: string | null | undefined): MsgKey {
  const k = `err.${code ?? 'server'}` as MsgKey
  return k in VI ? k : 'err.server'
}
